import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class EvidenceOrigin(str, Enum):
    """
    Mandatory statutory classification of every evidence record.
    Prevents AI-generated observations from being presented as primary source evidence.
    """
    PRIMARY_SOURCE   = "PRIMARY_SOURCE"    # Directly submitted or captured (URL, image, description)
    OCR_EXTRACTED    = "OCR_EXTRACTED"     # Text extracted from images via OCR
    SUBMITTED_TEXT   = "SUBMITTED_TEXT"    # Officer-submitted product description / notes
    AI_ANALYSIS      = "AI_ANALYSIS"       # Output of AI/NLP analysis — NOT primary source
    SYSTEM_GENERATED = "SYSTEM_GENERATED"  # Audit/metadata records generated by the platform


class EvidenceType(str, Enum):
    URL              = "URL"
    IMAGE            = "IMAGE"
    OCR_TEXT         = "OCR_TEXT"
    SUBMITTED_TEXT   = "SUBMITTED_TEXT"
    EXTRACTED_DATA   = "EXTRACTED_DATA"
    AI_ANALYSIS_NOTE = "AI_ANALYSIS_NOTE"


INTEGRITY_NOTE = (
    "This evidence package was assembled from stored records only. "
    "Primary source evidence (URLs, images, submitted text, OCR text) is clearly "
    "distinguished from AI analysis notes. AI analysis notes are marked with "
    "ai_generated=true and must NOT be treated as primary evidentiary facts. "
    "All records include capture timestamps and source references for full traceability."
)


class EvidenceRecord(BaseModel):
    """
    A single, classified evidence artifact.
    The evidence_origin and ai_generated fields enforce strict separation between
    primary source evidence and AI-generated analysis observations.
    """
    record_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    evidence_type: EvidenceType
    evidence_origin: EvidenceOrigin
    ai_generated: bool = Field(
        ...,
        description=(
            "True if this record is produced by AI/NLP analysis. "
            "Must be prominently displayed in any UI rendering this record."
        ),
    )
    content_text: Optional[str] = Field(
        None,
        description="Verbatim text content (for URL, OCR_TEXT, SUBMITTED_TEXT, AI_ANALYSIS_NOTE)",
    )
    content_uri: Optional[str] = Field(
        None,
        description="Storage URI or URL (for IMAGE, URL evidence types)",
    )
    source_type: str = Field(..., description="ECOMMERCE_URL, PACKAGING_OCR, OFFICER_DESCRIPTION, MANUAL_INPUT, etc.")
    source_reference: Optional[str] = Field(None, description="Original URL, file path, or record ID")
    sha256_hash: Optional[str] = Field(None, description="Cryptographic integrity hash (present for images/documents)")
    capture_timestamp: Optional[datetime] = None
    confidence: Optional[float] = Field(None, ge=0.0, le=1.0)
    metadata: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(use_enum_values=True)


class FindingEvidenceBundle(BaseModel):
    """
    All evidence linked to a single finding.
    Supports the statutory 4-tier chain of custody:
    FINDING -> WHY FLAGGED -> SOURCE -> ORIGINAL EVIDENCE
    Primary source evidence and AI analysis notes are stored in separate lists
    to prevent conflation.
    """
    finding_id: uuid.UUID
    finding_title: str
    severity: str
    source: str
    why_flagged: str
    rule_code: Optional[str] = None
    statutory_reference: Optional[str] = None
    source_metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Provenance of the source: platform, channel, seller, capture timestamp, or image asset ID",
    )
    primary_evidence: List[EvidenceRecord] = Field(
        default_factory=list,
        description="Raw source records: OCR text, URL snippets, submitted text, image references. origin != AI_ANALYSIS.",
    )
    ai_analysis_notes: List[EvidenceRecord] = Field(
        default_factory=list,
        description=(
            "AI/NLP-generated observations supporting this finding. "
            "MUST be displayed with a clear AI label and NOT treated as primary evidence."
        ),
    )

    model_config = ConfigDict(from_attributes=True)


class CaseEvidencePackage(BaseModel):
    """
    Comprehensive, structured evidence package for a case.
    Aggregates all evidentiary material from all sources with full provenance.
    """
    case_id: uuid.UUID
    case_number: str
    product_id: uuid.UUID
    product_name: Optional[str]
    brand: Optional[str] = None
    category: Optional[str] = None
    submission_timestamp: Optional[datetime]

    # Evidence categorized by primary type
    url_evidence: List[EvidenceRecord] = Field(default_factory=list)
    image_evidence: List[EvidenceRecord] = Field(default_factory=list)
    ocr_evidence: List[EvidenceRecord] = Field(default_factory=list)
    submitted_text_evidence: List[EvidenceRecord] = Field(default_factory=list)
    extracted_data_evidence: List[EvidenceRecord] = Field(default_factory=list)

    # Per-finding bundles (Hierarchy: Finding -> Why Flagged -> Source -> Original Evidence)
    finding_bundles: List[FindingEvidenceBundle] = Field(default_factory=list)

    # Summary metrics
    total_evidence_records: int = 0
    total_findings_with_evidence: int = 0
    coverage_percentage: float = 0.0
    generated_at: datetime

    # Cryptographic integrity note
    integrity_note: str = Field(default=INTEGRITY_NOTE)

    model_config = ConfigDict(from_attributes=True)


class EvidenceIntegrityCheckResult(BaseModel):
    """
    Statutory audit evaluation verifying cryptographic hashes, finding coverage,
    timestamp monotonicity, and strict separation of AI statements from source facts.
    """
    case_id: uuid.UUID
    case_number: str
    all_findings_linked: bool
    total_findings: int
    findings_with_evidence: int
    ai_separation_verified: bool
    unmarked_ai_items_found: int
    hash_verification_passed: bool
    total_hashed_items: int
    valid_hashes: int
    timestamps_valid: bool
    integrity_score: float = Field(..., ge=0.0, le=100.0)
    verification_details: List[str] = Field(default_factory=list)
    verified_at: datetime

    model_config = ConfigDict(from_attributes=True)
