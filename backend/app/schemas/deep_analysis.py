import uuid
from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class AnalysisEvidenceDTO(BaseModel):
    """Digital or textual evidentiary item supporting a compliance finding."""
    evidence_type: str = Field(..., description="TEXT_SNIPPET, IMAGE_CROP, DOM_NODE, CROSS_SOURCE_DIFF")
    caption: str
    text_snippet: Optional[str] = None
    source_reference: Optional[str] = None
    metadata_json: Dict[str, Any] = Field(default_factory=dict)


class AnalysisFindingDTO(BaseModel):
    """Discrete, structured compliance or consistency finding generated by an analysis module."""
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    finding_title: str
    description: str
    severity: str = Field(..., description="INFO, LOW, MEDIUM, HIGH, CRITICAL")
    confidence: float = Field(..., ge=0.0, le=1.0)
    source: str = Field(..., description="PACKAGING_LABEL, ECOMMERCE_WEB, OFFICER_DESCRIPTION, CROSS_SOURCE_COMPARISON")
    rule_code: Optional[str] = None
    statutory_reference: Optional[str] = None
    discrepancy_details: Optional[Dict[str, Any]] = None
    evidence_items: List[AnalysisEvidenceDTO] = Field(default_factory=list)


class ModuleResultDTO(BaseModel):
    """Structured execution output from an individual deep analysis module."""
    module_name: str
    status: str = Field(default="COMPLETED", description="COMPLETED, PARTIAL, FAILED")
    confidence: float = Field(..., ge=0.0, le=1.0)
    severity_suggestion: str = Field(default="INFO", description="INFO, LOW, MEDIUM, HIGH, CRITICAL")
    findings: List[AnalysisFindingDTO] = Field(default_factory=list)
    evidence: List[AnalysisEvidenceDTO] = Field(default_factory=list)
    details: Dict[str, Any] = Field(default_factory=dict)


class DeepAnalysisReportResponse(BaseModel):
    """Complete aggregated deep product analysis report spanning all 5 analytical dimensions."""
    case_id: uuid.UUID
    product_id: uuid.UUID
    case_number: str
    total_checks: int
    total_findings: int
    critical_findings_count: int
    high_findings_count: int
    medium_findings_count: int
    low_findings_count: int
    info_findings_count: int
    modules: Dict[str, ModuleResultDTO]
    execution_timestamp: datetime
    orchestrator_version: str = "v1.0-DRISHTI-DeepAnalysis"

    model_config = ConfigDict(from_attributes=True)
